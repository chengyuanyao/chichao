import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('./visual_benchmark.html',import.meta.url),'utf8');
const helper=source.match(/function destroyFixtureStructures\([^]*?\n}/)[0];
const structures=Array.from({length:15},(_,i)=>({id:'s'+i,kind:i===8?'mhq':'factory',owner:i<8?'steel':'magic',x:i*100,y:200,size:58}));
const units=[{id:'u0'}];
const fixture={game:{structures,units},syntheticEffects:[]};
vm.createContext(fixture);vm.runInContext(helper,fixture);
fixture.destroyFixtureStructures(1,'mhq');
assert.equal(fixture.syntheticEffects[0].entityId,'s8');
assert.equal(fixture.syntheticEffects[0].owner,'magic');
assert.equal(fixture.syntheticEffects[0].wreck,true);
assert.equal(fixture.game.structures.length,14);
assert.strictEqual(fixture.game.units,units,'benchmark destruction leaves unit workload intact');
fixture.destroyFixtureStructures(15);
assert.equal(fixture.game.structures.length,0);
assert.equal(fixture.syntheticEffects.length,15);
assert.equal(new Set(fixture.syntheticEffects.map(e=>e.entityId)).size,15,'one confirmed event per building');
fixture.destroyFixtureStructures(15);assert.equal(fixture.syntheticEffects.length,15);
assert.match(source,/fixedFrame===120\) destroyFixtureStructures/);
assert.match(source,/\[121,150,180,300\]/,'observe active, finishing and retired states');
assert.match(source,/fixedFrame>=121&&fixedFrame<=180/,'separate death-window timing');
console.log('Visual benchmark: exact destruction events, unchanged army, fixed trigger and bounded death-window sampling passed.');
